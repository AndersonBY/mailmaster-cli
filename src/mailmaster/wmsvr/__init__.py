"""Wmsvr / Coremail Wzp private protocol package.

Wire format (confirmed from `mastercore.dll` disassembly and live captures):
  - Each TLV record: `[2-byte tag BE] [LEB128 length] [raw value]`
  - Request JSON (or raw binary for attachment chunks) rides in slice1 separately from the TLV envelope in slice0
  - Encrypted d1 frames carry AES-128-CBC (PKCS#7 padded) slices over raw TCP (ports 443/8080)

Production transport status:
  - The raw d1 transport (`keys.py`, `d1_wire.py`, `payloads.py`, `login.py`) plus
    `WmsvrMailSession` (`session.py`, `operations.py`, `lz4.py`) is the verified production
    private-protocol path for Wmsvr / 163 mailbox reads, mutations, drafts, sends, and
    attachment uploads.
  - Legacy HTTP request/header helpers in `diagnostics.py` are kept only as offline
    reverse-engineering and analysis scaffolding.
"""

